package com.mo.swtp.common.operation;

/**
 * 운전모드 ({@code operation.drvmd_chg_h.bf_drvmd_cd} / {@code af_drvmd_cd}) —
 * <b>설비 상태 변경 명령을 누가 만드는가</b>의 축이다.
 *
 * <p>"설비를 누가 제어하는가"가 아니라는 점이 중요하다. PLC의 로컬 인터록과 시퀀스는 이 축이
 * 규정하는 대상이 아닌 하위 레이어이고, 운전모드가 무엇이든 그것은 계속 돈다.
 * 이 enum이 정하는 것은 <b>플랫폼이 설비 상태를 바꾸는 명령을 누가 발의하는가</b>다.
 *
 * <p><b>별도의 "수동" 모드를 두지 않는 이유</b>: {@link #AI_ANLS}가 곧 수동이다.
 * 아키텍처 11.3이 적어 둔 "자동/수동/원격"은 제어 <i>주체</i>의 축이고 이것은 명령 <i>생성자</i>의
 * 축이라 서로 다르다("원격"은 접속 경로 축이라 아예 다른 이야기다). 두 축을 한 컬럼에 겹쳐 담으면
 * "AI분석이면서 자동"과 "AI분석이면서 수동"을 구분할 수 없게 되는데, 앞의 조합은 존재하지 않는다 —
 * AI가 개입하지 않는 동안 플랫폼이 스스로 명령을 만드는 경우가 없기 때문이다.
 *
 * <p><b>제어대상 유형과 무관하게 같은 집합을 쓴다.</b> {@link ControlTargetType#CTRL_GRP}(EMS 제어그룹)든
 * {@link ControlTargetType#PRCS}(자율운영 공정)든 3값을 공유하므로 검증이 이 enum 하나로 끝난다.
 *
 * <p><b>모드를 바꾸는 것은 언제나 사람이다.</b> {@link IssuerService}는 그 사람이 어느 서비스를
 * 통해 바꿨는지를, {@code rgstr_id}는 누구인지를 남긴다. 시스템이 스스로 모드를 낮추는
 * 방어 로직은 현재 없으며, 제어 경로를 붙일 때 도입 여부를 정한다.
 *
 * <p><b>초기값은 {@link #AI_ANLS}이며 초기 이력 행을 만들지 않는다.</b>
 * 이력이 없다 = 한 번도 바뀌지 않았다 = {@code AI_ANLS}다. 새로 등록된 설비가 등록되자마자
 * AI 제어를 받으면 안 되므로 이것이 안전한 기본값이다. 첫 전환 행의 {@code bf_drvmd_cd}에
 * {@code AI_ANLS}를 넣으면 되고, {@code INIT} 같은 특수값은 두지 않는다 —
 * "설비가 지금 INIT 모드다"는 말이 성립하지 않기 때문이다.
 *
 * <p>상수명이 곧 DB 코드값이다({@code @Enumerated(EnumType.STRING)}). 별도 코드 필드를 두면
 * 두 값이 어긋날 수 있고 동기화할 이유가 없다. 컬럼이 {@code VARCHAR(10)}이라
 * {@code AI_RECOMMEND}(12자)는 들어가지 않으므로 표준단어사전의 {@code RCMD}(추천)·{@code ANLS}(분석)로
 * 조합했다.
 *
 * <p>한글 표시명을 담지 않는다 — {@code ErrorCode}가 세운 계약("표현은 프론트가 코드값 기반 i18n으로
 * 책임진다")을 따른다.
 *
 * @see ChangeReason 전환 사유
 */
public enum DrivenMode {

    /**
     * AI분석 — AI는 분석만 제공하고 현상태를 유지한다. 제어할 일이 생기면 사람이 제어한다.
     *
     * <p>안전한 기본값이자 모든 하향 전환의 종착지다.
     * {@link ChangeReason#COMM_FAIL}처럼 AI가 응답하지 않는 상황에서는 실질적으로 이 모드와 같아진다 —
     * 다만 <b>모드를 실제로 내리는 것은 사람</b>이며, 시스템이 스스로 낮추는 경로는 현재 없다.
     */
    AI_ANLS,

    /**
     * AI추천 — AI가 선택한 설비 상태를 사람에게 추천하고, 사람이 승인하면 그 상태로 변경한다.
     *
     * <p>이 모드는 <b>승인되지 않은 추천</b>이라는 데이터를 만든다. 그 기록은 운전모드 이력이 아니라
     * 제어 명령 쪽에 남아야 한다 — 모드가 바뀌지 않기 때문이다. 승인률은 {@link #AI}로 올릴지를
     * 판단하는 정량 근거이므로 거부된 추천은 버리는 데이터가 아니다.
     */
    AI_RCMD,

    /** AI — AI가 분석한 대로 설비를 운영한다. */
    AI;

    /**
     * 자율성 수준 — 낮을수록 사람이 명령을 만든다. 오름차순으로 고유하다.
     *
     * <p><b>전이 허용 여부를 이 enum이 판단하지 않는다.</b> 방향 판정에 필요한 최소 수단만 제공하고
     * 정책은 서비스 계층에 둔다. 하향(자율성 감소)은 어디서든 즉시 가능해야 하고
     * — 인터록 발동 시 {@code AI} → {@code AI_ANLS} 직행이 막히면 안 된다 —
     * 상향은 단계적 진행을 권장하되 강제하지 않는다. 정비 후 복귀처럼 이미 검증된 대상을
     * 되돌리는 정당한 경우가 있어, 막아 두면 그때 운영이 멈춘다.
     * 근거는 {@code bf}/{@code af}로 이력에 남으므로 사후 감사로 충분하다.
     */
    public int level() {
        return ordinal();
    }
}
