package com.mo.swtp.common.operation;

/**
 * 운전모드 변경사유 ({@code operation.drvmd_chg_h.chg_rsn_cd}) — NOT NULL이다.
 *
 * <p>"운전원이 AI 자동을 왜 껐나"는 사고 조사의 첫 질문이고 {@code bf}/{@code af} 코드만으로는
 * 답이 나오지 않는다. {@link DrivenMode#AI_ANLS}가 "AI 미개입"으로 확정되면서
 * <b>하향 사유가 곧 AI 신뢰도 지표</b>가 됐다 — "이상감지로 인한 강등이 월 몇 건인가"가
 * 자율운영 성숙도의 1차 척도다.
 *
 * <p><b>모드 전환은 언제나 사람이 한다.</b> 따라서 아래 사유들은 "시스템이 자동으로 내린 조건"이
 * 아니라 <b>"그 일이 생겨서 운전원이 내린 근거"</b>다. 시스템이 스스로 모드를 낮추는 경로는
 * 현재 설계에 없다 — AI가 응답하지 않으면 명령이 나가지 않아 현상태가 유지되고,
 * 모드를 내리는 것은 사람의 판단이다. 자동 강등(방어 로직) 도입 여부는 제어 경로를 붙일 때 함께 정한다.
 *
 * <p><b>"최소로 시작해 늘린다"를 따르지 않았다.</b> 일반 마스터라면 그것이 맞지만 이력 테이블은
 * 반대다. 사유가 부족하면 전부 {@link #ETC}로 몰리고, 나중에 코드를 추가해도
 * <b>이미 쌓인 {@code ETC} 행은 재분류할 수 없다.</b> 통계가 영구히 망가지는 쪽이
 * 코드 몇 개를 미리 두는 것보다 비싸다.
 *
 * <p>코드로 표현되지 않는 서술은 {@code chg_rsn_rmrk}(비고, NULL 허용)에 담는다.
 * {@link #ETC}를 쓸 때는 비고가 사실상 필수다.
 *
 * <p>상수명이 곧 DB 코드값이며 컬럼은 {@code VARCHAR(10)}이다.
 * 한글 표시명은 담지 않는다 — 표현은 프론트가 코드값 기반 i18n으로 책임진다.
 *
 * @see DrivenMode 운전모드
 */
public enum ChangeReason {

    /** 운전원판단 — 특별한 사건 없이 운전원이 결정했다. 실제로 가장 흔할 코드다. */
    OPRTR,

    /**
     * 승인상향 — 검증 결과를 확인하고 자율성을 올렸다.
     *
     * <p>{@link DrivenMode#AI_RCMD}에서 {@link DrivenMode#AI}로 올릴 때의 근거는
     * 그 구간에 쌓인 추천 승인률이다.
     */
    APRV,

    /** 이상감지 — 수질·유량 등 공정값이 허용 범위를 이탈했다. */
    ANOMALY,

    /** 인터록 — 안전 인터록이 발동했다. 이 경우 하향은 즉시여야 하며 단계를 건너뛴다. */
    ITLCK,

    /**
     * 모델성능저하 — 예측 오차가 임계를 넘어 AI 판단을 신뢰할 수 없다.
     *
     * <p>모델은 계절·수질 변화로 성능이 떨어진다. 이것을 {@link #ETC}로 받으면
     * <b>재학습 시점을 데이터로 판단할 수 없다.</b>
     *
     * <p>AI가 스스로 "이번 판단은 확신이 낮다"고 내려가는 경우(신뢰도 미달)도 당분간 여기에 담는다.
     * 지속적 성능 저하와 시점 성격이 다르지만, 구분 실익이 확인되기 전에 코드를 늘리지 않는다.
     */
    MDL_DGRD,

    /**
     * 계측이상 — AI <b>입력</b>이 오염됐다. 센서 고장·계측값 이상 등.
     *
     * <p>{@link #MDL_DGRD}와 구분하는 것이 핵심이다. <b>입력이 나쁜 것</b>과 <b>모델이 나쁜 것</b>은
     * 대응이 완전히 다르다(센서 교체 vs 재학습). 한 코드로 합치면 그 판단을 이력에서 복원할 수 없다.
     */
    SNSR_FAIL,

    /**
     * 통신두절 — {@code ai-service} 응답이 없어 운전원이 모드를 내렸다.
     *
     * <p>별도 FastAPI 프로세스라 두절은 확정적으로 일어난다. 이때 AI는 명령도 추천도 만들지
     * 못하므로 설비는 현상태를 유지한다 — 즉 실질은 이미 {@link DrivenMode#AI_ANLS}와 같고,
     * 모드를 실제로 내리는 것은 그 사실을 확인한 사람이다.
     */
    COMM_FAIL,

    /** 스케줄 — 사전 정의된 시간대에 따른 전환. */
    SCHED,

    /** 정비 — 설비 점검·보수. */
    MAINT,

    /** 시운전 — 검증·시험 운전. */
    TEST,

    /** 기타 — 위에 해당하지 않는 사유. 비고({@code chg_rsn_rmrk})를 반드시 함께 남긴다. */
    ETC
}
